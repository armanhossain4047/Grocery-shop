    private void CreateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_CreateBtnActionPerformed

        if (accounttypeCMB.getSelectedItem().toString().isEmpty() || ledgernameTbl.getText().isEmpty() || addressTbl.getText().isEmpty() || mobileTbl.getText().isEmpty() || openingbalanceTbl.getText().isEmpty()) {
            JOptionPane.showMessageDialog(null, "Please fill in all fields", "Quick ledger", JOptionPane.ERROR_MESSAGE);
        } else if (!openingbalanceTbl.getText().matches("\\d+") || !mobileTbl.getText().matches("\\d+")) {
            JOptionPane.showMessageDialog(null, "Opening balance and mobile fields should contain only numbers", "Quick ledger", JOptionPane.ERROR_MESSAGE);
        } else {
            int Ladger_Found = 0;
            try {
                Class.forName("com.mysql.jdbc.Driver");
                Connection connection = (Connection) DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");
                Statement statement = (Statement) connection.createStatement();
                ResultSet result = statement.executeQuery("SELECT * FROM `accountinfo` WHERE AccountType = '" + accounttypeCMB.getSelectedItem().toString() + "' and LadgerName = '" + ledgernameTbl.getText() + "'");
                while (result.next()) {
                    Ladger_Found = 1;
                }
                result.next();
                connection.close();

                statement.close();

            } catch (Exception ex) {
            }
            if (Ladger_Found == 1) {
                JOptionPane.showMessageDialog(this, ledgernameTbl.getText() + "! is also found please write a different name.");
            } else {
                try {
                    Class.forName("com.mysql.jdbc.Driver");
                    Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");
                    java.sql.PreparedStatement ps = (java.sql.PreparedStatement) connection.prepareStatement("INSERT INTO accountinfo (AccountType, LadgerName,Address,Mobile,OpenBalance)Values(?,?,?,?,?)");
                    ps.setString(1, accounttypeCMB.getSelectedItem().toString());
                    ps.setString(2, ledgernameTbl.getText());
                    ps.setString(3, addressTbl.getText());
                    ps.setString(4, mobileTbl.getText());
                    ps.setString(5, openingbalanceTbl.getText());
                    ps.executeUpdate();
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, e);
                }
                try {
                    Class.forName("com.mysql.jdbc.Driver");
                    Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");
                    PreparedStatement ps = (PreparedStatement) connection.prepareStatement("INSERT INTO ladger (AccountType, Name,Address,Mobile,Blance)Values(?,?,?,?,?)");
                    ps.setString(1, accounttypeCMB.getSelectedItem().toString());
                    ps.setString(2, ledgernameTbl.getText());
                    ps.setString(3, addressTbl.getText());
                    ps.setString(4, mobileTbl.getText());
                    ps.setString(5, openingbalanceTbl.getText());
                    ps.executeUpdate();
                    ledgernameTbl.setText(null);
                    addressTbl.setText(null);
                    mobileTbl.setText(null);
                    openingbalanceTbl.setText(null);
                    JOptionPane.showMessageDialog(this, "Ladger Create Successfully");
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            }

        }

    }//GEN-LAST:event_CreateBtnActionPerformed

