    private void ChangeBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ChangeBtnActionPerformed
      if (CurrentPasswordTbl.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please Enter Current Password");
} else if (PasswordTbl.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please Enter New Password");
} else if (ConfirmPasswordTbl.getText().isEmpty()) {
    JOptionPane.showMessageDialog(this, "Please Enter Confirm Password");
} else {
    try {
        Class.forName("com.mysql.jdbc.Driver");
         java.sql.Connection connection = java.sql.DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");
            PreparedStatement ps = (PreparedStatement) connection.prepareStatement("UPDATE PasswordTbl SET Password = ? WHERE Password = ?");
            ps.setString(1, ConfirmPasswordTbl.getText());  // New password
            ps.setString(2, CurrentPasswordTbl.getText());  // Current password
            int rowsAffected = ps.executeUpdate();
            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Password Change Successfully");
                CurrentPasswordTbl.setText(null);
                PasswordTbl.setText(null);
                ConfirmPasswordTbl.setText(null);
            } else {
                JOptionPane.showMessageDialog(this, "Current Password Incorrect or No records found for the provided password.");
            }
            ps.close();
        
    } catch ( Exception e) {
        JOptionPane.showMessageDialog(this, e);
    }
}

    }//GEN-LAST:event_ChangeBtnActionPerformed

