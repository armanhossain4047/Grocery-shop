    private void GroupNameUpdateBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GroupNameUpdateBtnActionPerformed

        if (OldGroupnameCmb.getSelectedItem().toString().equals("Select")) {
            JOptionPane.showMessageDialog(this, "Please Select GroupName");
        } else if (NewGroupNameTbl.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter New Group Name");
        } else {
            try {
                Class.forName("com.mysql.jdbc.Driver");
                Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");
                PreparedStatement ps = (PreparedStatement) connection.prepareStatement("UPDATE groupname SET  GroupName = ? WHERE GroupName = '" + OldGroupnameCmb.getSelectedItem().toString() + "'");
                ps.setString(1, NewGroupNameTbl.getText());
                ps.executeUpdate();
                JOptionPane.showMessageDialog(this, "GroupName Updated");
                NewGroupNameTbl.setText(null);
                OldGroupnameCmb.setSelectedItem("Select");
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, e);
            }
        }

    }//GEN-LAST:event_GroupNameUpdateBtnActionPerformed

    private void OldGroupnameCmbAncestorAdded(javax.swing.event.AncestorEvent evt) {//GEN-FIRST:event_OldGroupnameCmbAncestorAdded
        try {
            OldGroupnameCmb.removeAllItems();
            OldGroupnameCmb.addItem("Select");
            Class.forName("com.mysql.jdbc.Driver");
            Connection connection1 = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");
            Statement statement1 = connection1.createStatement();
            ResultSet result1 = statement1.executeQuery("SELECT * FROM groupname");
            while (result1.next()) {
                String Name = result1.getString(2);
                OldGroupnameCmb.addItem(Name);
            }
            connection1.close();
            statement1.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e);
        }
    }//GEN-LAST:event_OldGroupnameCmbAncestorAdded

