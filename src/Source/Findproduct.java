    private void updateTable(JTable table, String query, String... params) throws Exception, ClassNotFoundException {
        DefaultTableModel model = (DefaultTableModel) table.getModel();
        model.setRowCount(0); // Clear table

        Class.forName("com.mysql.jdbc.Driver");
        try (Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", ""); PreparedStatement statement = (PreparedStatement) connection.prepareStatement(query)) {
            for (int i = 0; i < params.length; i++) {
                statement.setString(i + 1, params[i]);
            }
            ResultSet result = statement.executeQuery();
            ResultSetMetaData rsmd = (ResultSetMetaData) result.getMetaData();
            int columnCount = rsmd.getColumnCount();

            while (result.next()) {
                Object[] row = new Object[columnCount];
                for (int i = 0; i < columnCount; i++) {
                    row[i] = result.getObject(i + 1);
                }
                model.addRow(row);
            }
        }
    }

