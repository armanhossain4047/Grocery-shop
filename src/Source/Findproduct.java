    private void BarcodeTblKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_BarcodeTblKeyReleased
        String barcode = BarcodeTbl.getText();
        if (barcode.isEmpty()) {
            GroupNameComboBox.setSelectedItem("Select");
            ProductNameJComboBox.setSelectedItem("Select");
            return;
        }

        String query = "SELECT * FROM `stock_enrty` WHERE Barcode = ?";
        try (Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", ""); PreparedStatement statement = (PreparedStatement) connection.prepareStatement(query)) {
            statement.setString(1, barcode);
            ResultSet result = statement.executeQuery();

            if (result.next()) {
                String itemName = result.getString(7);
                String groupName = result.getString(8);
                GroupNameComboBox.setSelectedItem(groupName);
                ProductNameJComboBox.setSelectedItem(itemName);
            } else {
                GroupNameComboBox.setSelectedItem("Select");
                ProductNameJComboBox.setSelectedItem("Select");
            }
        } catch (Exception ex) {
            ex.printStackTrace(); // Log the exception
        }
    }//GEN-LAST:event_BarcodeTblKeyReleased

