    String BarcodeGenarate() {
        String total_rows1 = null;
        try {
            Class.forName("com.mysql.jdbc.Driver");
            Connection connection = (Connection) DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");
            java.sql.Statement statement = (java.sql.Statement) connection.createStatement();
            ResultSet result = statement.executeQuery("SELECT COUNT(*) AS total_rows FROM stock_enrty");
            result.next();
            total_rows1 = result.getString("total_rows");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Barcode Genarate Problem!");
        }
        return total_rows1;
    }

