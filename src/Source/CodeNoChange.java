    private void ChangeBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ChangeBtnActionPerformed
        if (OldCodeTbl.getText().toString().equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter Old Barcode");
        } else if (NewCodeTbl.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter New Barcode");
        } else {
            try {
                Class.forName("com.mysql.jdbc.Driver");
                Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", "");

                // Prepare the SQL statement for updating the stock_enrty table
                PreparedStatement ps1 = (PreparedStatement) connection.prepareStatement("UPDATE stock_enrty SET Barcode = ? WHERE Barcode = ?");
                ps1.setString(1, NewCodeTbl.getText());  // Set the new barcode
                ps1.setString(2, OldCodeTbl.getText().toString());  // Set the old barcode
                ps1.executeUpdate();  // Execute the update for stock_enrty table

                // Prepare the SQL statement for updating the purchase table
                PreparedStatement ps2 = (PreparedStatement) connection.prepareStatement("UPDATE purchase SET Barcode = ? WHERE Barcode = ?");
                ps2.setString(1, NewCodeTbl.getText());  // Set the new barcode
                ps2.setString(2, OldCodeTbl.getText().toString());  // Set the old barcode
                ps2.executeUpdate();  // Execute the update for purchase table

                // Prepare the SQL statement for updating the purchase_statement table
                PreparedStatement ps3 = (PreparedStatement) connection.prepareStatement("UPDATE purchase_statement SET Barcode = ? WHERE Barcode = ?");
                ps3.setString(1, NewCodeTbl.getText());  // Set the new barcode
                ps3.setString(2, OldCodeTbl.getText().toString());  // Set the old barcode
                ps3.executeUpdate();  // Execute the update for purchase_statement table

                // Show a success message
                JOptionPane.showMessageDialog(this, "Barcode Change");

                // Reset input fields
                NewCodeTbl.setText(null);
                OldCodeTbl.setText(null);  // Assuming setText is correct instead of getText

                // Close the prepared statements and connection
                ps1.close();
                ps2.close();
                ps3.close();
                connection.close();

            } catch (Exception e) {
                // Show an error message if something goes wrong
                JOptionPane.showMessageDialog(this, e);
            }
        }


    }//GEN-LAST:event_ChangeBtnActionPerformed

