    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
   
        
        try {
        String accounttype = (String) accounttypeCMB.getSelectedItem();
        String ledgername = ledgernameTbl.getText();
        String address = addressTbl.getText();
        String mobile = mobileTbl.getText();
        String openingbalance = openingbalanceTbl.getText();

    if (accounttype.isEmpty() || ledgername.isEmpty() || address.isEmpty() || mobile.isEmpty() || openingbalance.isEmpty()) {
        JOptionPane.showMessageDialog(null, "Please fill in all fields", "Quick ledger", JOptionPane.ERROR_MESSAGE);
        return;
    }

    Class.forName("net.ucanaccess.jdbc.UcanaccessDriver");
    String url = "jdbc:ucanaccess://Database.accdb";
    String query = "INSERT INTO ledgerTBL (accounttype, ledgername, address,mobile,openingbalance) VALUES (?,?,?,?,?)";

    try (Connection connection = DriverManager.getConnection(url);
         PreparedStatement preparedStatement = connection.prepareStatement(query)) {

        preparedStatement.setString(1, accounttype);
        preparedStatement.setString(2, ledgername);
        preparedStatement.setString(3, address);
        preparedStatement.setString(4, mobile);
        preparedStatement.setString(5, openingbalance);

        preparedStatement.executeUpdate();

        ledgernameTbl.setText(null);
        addressTbl.setText(null);
        mobileTbl.setText(null);
        openingbalanceTbl.setText(null);
        
        JOptionPane.showMessageDialog(null, "Successfully", "Quick ledger", JOptionPane.INFORMATION_MESSAGE);

    } catch (Exception e) {
        JOptionPane.showMessageDialog(null, "Error inserting data: " + e.getMessage(), "Quick ledger Error", JOptionPane.ERROR_MESSAGE);
    }

} catch (ClassNotFoundException e) {
    JOptionPane.showMessageDialog(null, "Driver not found", "Error", JOptionPane.ERROR_MESSAGE);
} finally {
    // Close resources in a finally block (not implemented in the provided code)
}



    }//GEN-LAST:event_jButton1ActionPerformed

