    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed

        String companyname, address, email, vat, mobile, Messages;
        Connection conn = null;
        PreparedStatement psUpdate = null;
        PreparedStatement psInsert = null;

        companyname = companynameTbl.getText();
        address = addressTbl.getText();
        email = emailTbl.getText();
        vat = vatTbl.getText();
        mobile = mobileTbl.getText();
        Messages = MessagesTbl.getText();

        try {
            // Load MySQL JDBC driver
            Class.forName("com.mysql.jdbc.Driver");

            // Establish connection
            String url = "jdbc:mysql://192.168.0.108/grocery_database";
            conn = DriverManager.getConnection(url, "root", "");

            // Start transaction
            conn.setAutoCommit(false);

            // Check if company exists for update
            String selectQuery = "SELECT * FROM companyinfo WHERE Name=?";
            psUpdate = conn.prepareStatement(selectQuery);
            psUpdate.setString(1, companyname);
            ResultSet rs = psUpdate.executeQuery();

            if (rs.next()) {
                // Company exists, update existing record
                String updateQuery = "UPDATE companyinfo SET Address=?, EMail=?, VAT=?, Mobile=?, Messages=? WHERE Name=?";
                psUpdate = conn.prepareStatement(updateQuery);
                psUpdate.setString(1, address);
                psUpdate.setString(2, email);
                psUpdate.setString(3, vat);
                psUpdate.setString(4, mobile);
                psUpdate.setString(5, Messages);
                psUpdate.setString(6, companyname);
                psUpdate.executeUpdate();
            } else {
                // Company does not exist, insert new record
                String insertQuery = "INSERT INTO companyinfo (Name, Address, EMail, VAT, Mobile, Messages) VALUES (?, ?, ?, ?, ?, ?)";
                psInsert = conn.prepareStatement(insertQuery);
                psInsert.setString(1, companyname);
                psInsert.setString(2, address);
                psInsert.setString(3, email);
                psInsert.setString(4, vat);
                psInsert.setString(5, mobile);
                psInsert.setString(6, Messages);
                psInsert.executeUpdate();
            }

            // Commit transaction
            conn.commit();

            // Clear input fields
            companynameTbl.setText(null);
            addressTbl.setText(null);
            emailTbl.setText(null);
            vatTbl.setText(null);
            mobileTbl.setText(null);
            MessagesTbl.setText(null);

            JOptionPane.showMessageDialog(this, "Update Successfully!");

            // Navigate to Home screen
            java.awt.EventQueue.invokeLater(() -> {
                new Home().setVisible(true);
            });

            dispose();  // Close current window

        } catch (ClassNotFoundException | SQLException e) {
            try {
                if (conn != null) {
                    conn.rollback();  // Rollback transaction if there's an exception
                }
            } catch (SQLException rollbackEx) {
                System.out.println("Error rolling back transaction: " + rollbackEx.getMessage());
            }

            System.out.println("Error: " + e.getMessage());
            e.printStackTrace(); // Print stack trace for debugging

            JOptionPane.showMessageDialog(this, "Error updating data: " + e.getMessage());

        } finally {
            try {
                // Close all resources
                if (psUpdate != null) {
                    psUpdate.close();
                }
                if (psInsert != null) {
                    psInsert.close();
                }
                if (conn != null) {
                    conn.setAutoCommit(true);  // Restore auto-commit mode
                    conn.close();
                }
            } catch (Exception ex) {
                System.out.println("Error closing resources: " + ex.getMessage());
            }
        }


    }//GEN-LAST:event_jButton1ActionPerformed

