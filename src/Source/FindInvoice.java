    public void populateComboBox(String InvoiceNumber) {
        // Example: Add the invoice number to the combo box
        InvoiceNoCmd.removeAllItems(); // Clear existing items
        InvoiceNoCmd.addItem(InvoiceNumber); // Add the provided invoice number

        // Optional: Fetch related data from the database and populate further
        try (Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", ""); PreparedStatement preparedStatement = (PreparedStatement) connection.prepareStatement(
                "SELECT RelatedData FROM invoices WHERE InvoiceNumber = ?")) {

            preparedStatement.setString(1, InvoiceNumber);

            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                while (resultSet.next()) {
                    String relatedData = resultSet.getString("RelatedData");
                    InvoiceNoCmd.addItem(relatedData); // Add fetched data to jComboBox1
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

