    void Print_Invoice() {
        DefaultTableModel model = (DefaultTableModel) jTable.getModel();
        // Sanitize and validate Login.Pc_Terminal if necessary
        String query = "INSERT INTO `invprint_p2` (SNo, invoiceNo, CName, DueAmount, Barcode, item, rate, qty, price, PaidAmount, DiscountTk, VAT, TotalSale, TotalBlance, Cash_Exchange, User) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?);";

        try (Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", ""); PreparedStatement ps = (PreparedStatement) connection.prepareStatement(query)) {

            for (int i = 0; i < model.getRowCount(); i++) {
                ps.setInt(1, i + 1); // Assuming SNo is an integer and auto-increment
                ps.setString(2, InvoiceNo.getText());
                ps.setString(3, CustomarNameTbl.getText());
                ps.setString(4, DueAmountTbl.getText());
                ps.setString(5, model.getValueAt(i, 2).toString());
                ps.setString(6, model.getValueAt(i, 3).toString());
                ps.setString(7, model.getValueAt(i, 4).toString());
                ps.setString(8, model.getValueAt(i, 5).toString());
                ps.setString(9, model.getValueAt(i, 6).toString());
                ps.setString(10, Double.toString(Double.parseDouble(PaidTbl.getText()) + Double.parseDouble(CardTbl.getText())));
                ps.setString(11, DiscountTkTbl.getText());
                ps.setString(12, VatTbl.getText());
                ps.setString(13, TotalSaleTbl.getText());
                ps.setString(14, BlanceTbl.getText());
                ps.setString(15, RetunTkTbl.getText());
                ps.setString(16, Login.UserBy);
                ps.addBatch();
            }
            ps.executeBatch();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
        Print_Customer_Copy();
    }

