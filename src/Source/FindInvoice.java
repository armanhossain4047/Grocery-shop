    public DefaultTableModel createTableModel() {
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("Date");
        model.addColumn("InvoiceNo");
        model.addColumn("Barcode");
        model.addColumn("ProductName");
        model.addColumn("Sale_Rate");
        model.addColumn("Qty");
        model.addColumn("Price");
        return model;
    }

    private void populateJTable(String invoiceNo) {
        String query = "SELECT Date, invoiceNo, Barcode, ProductName, Sale_Rate, Qty, Price FROM invaudit WHERE invoiceNo = ?";
        DefaultTableModel tableModel = createTableModel();

        try (Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", ""); PreparedStatement preparedStatement = (PreparedStatement) connection.prepareStatement(query)) {

            preparedStatement.setString(1, invoiceNo);
            try (ResultSet resultSet = preparedStatement.executeQuery()) {
                while (resultSet.next()) {
                    Object[] row = new Object[]{
                        resultSet.getDate("Date"),
                        resultSet.getString("invoiceNo"),
                        resultSet.getString("Barcode"),
                        resultSet.getString("ProductName"),
                        resultSet.getDouble("Sale_Rate"),
                        resultSet.getInt("Qty"),
                        resultSet.getDouble("Price")
                    };
                    tableModel.addRow(row);
                }
            }
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
            ex.printStackTrace();
        }

        jTable.setModel(tableModel);
    }


    private void InvoiceNoCmdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_InvoiceNoCmdActionPerformed
        String selectedInvoiceNo = (String) InvoiceNoCmd.getSelectedItem();
        if (selectedInvoiceNo != null && !"Select".equals(selectedInvoiceNo)) {
            String query = "SELECT * FROM invoice_count WHERE InvoiceNo = ?";
            try (Connection connection = DriverManager.getConnection("jdbc:mysql://192.168.0.108/grocery_database", "root", ""); PreparedStatement preparedStatement = (PreparedStatement) connection.prepareStatement(query)) {

                preparedStatement.setString(1, selectedInvoiceNo);
                try (ResultSet resultSet = preparedStatement.executeQuery()) {
                    if (resultSet.next()) {
                        CustomarNameTbl.setText(resultSet.getString("CustomerName"));
                        DueAmountTbl.setText(resultSet.getString("DueAmount"));
                        DiscountTkTbl.setText(resultSet.getString("DiscountTk"));
                        PaidTbl.setText(resultSet.getString("Cash"));
                        CardTbl.setText(resultSet.getString("Digital_Payment"));
                        VatTbl.setText(resultSet.getString("VAT"));
                        TotalSaleTbl.setText(resultSet.getString("TotalBlance"));
                        RetunTkTbl.setText(resultSet.getString("Cash_Exchange"));
                        UserTbl.setText(resultSet.getString("User"));
                    }
                }

                populateJTable(selectedInvoiceNo);
            } catch (SQLException ex) {
                JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
                ex.printStackTrace();
            }
        }

    }//GEN-LAST:event_InvoiceNoCmdActionPerformed

